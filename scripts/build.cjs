'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const args = process.argv.slice(2);
for (const arg of args)
  if (!['--release', '--host-qa'].includes(arg)) throw new Error('Unknown build argument: ' + arg);
const hostQA = args.includes('--host-qa');
if (hostQA && args.includes('--release'))
  throw new Error('Host QA must never be included in a release build');
const names = ['core', 'ui', 'editor', 'reading', 'plugin'];
const modules = names
  .map(
    (name) =>
      `${JSON.stringify('./' + name)}: function(module, exports, require) {\n${fs.readFileSync(path.join(root, 'src', name + '.js'), 'utf8')}\n}`,
  )
  .join(',\n');
let output = `// Flow Edit. Generated by node build.js.\n'use strict';\nconst external = require;\nconst modules = {${modules}};\nconst cache = {};\nfunction load(id) {\n if (!modules[id]) return external(id);\n if (cache[id]) return cache[id].exports;\n const m = { exports: {} }; cache[id] = m; modules[id](m, m.exports, load); return m.exports;\n}\nmodule.exports = load('./plugin');\n`;
if (hostQA) {
  const qa = fs.readFileSync(path.join(__dirname, 'host-qa.cjs'), 'utf8');
  output += `\n// Temporary, opt-in host verification command. Not part of release builds.\nconst qaModule={exports:{}};\n(function(module,exports,require){${qa}\n})(qaModule,qaModule.exports,load);\nconst originalOnload=module.exports.prototype.onload;\nmodule.exports.prototype.onload=async function(){await originalOnload.call(this);this.addCommand({id:'verify-installed-fixes',name:'开发验证（仅测试插件笔记）',callback:()=>qaModule.exports(this)});};\n`;
}
const targetRoot = hostQA ? path.join(root, '.host-build', 'flow-edit') : root;
fs.mkdirSync(targetRoot, { recursive: true });
fs.writeFileSync(path.join(targetRoot, 'main.js'), output);
if (hostQA)
  for (const name of ['manifest.json', 'styles.css'])
    fs.copyFileSync(path.join(root, name), path.join(targetRoot, name));
if (process.argv.includes('--release')) {
  const target = path.join(root, 'release', 'flow-edit');
  fs.mkdirSync(target, { recursive: true });
  for (const name of ['main.js', 'manifest.json', 'styles.css', 'README.md', 'LICENSE'])
    fs.copyFileSync(path.join(root, name), path.join(target, name));
  require('./validate.cjs').validateRelease(target);
}
console.log(
  hostQA
    ? 'Built isolated development verifier in .host-build/flow-edit/.'
    : 'Built main.js (Obsidian and CodeMirror remain host-provided).',
);
